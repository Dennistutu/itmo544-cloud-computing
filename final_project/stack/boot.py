"""The boot script each instance runs at first start, written in Python (no bash, Section 11.1).

build_boot_script() is a pure function: it returns the text of a Python program that
cloud-init runs as user-data. The program writes the tier's code, installs Python 3.11
and the libraries, writes the settings file, and starts the app as a systemd service.
It calls programs with subprocess and an argument list, never through a shell.

User-data is sent gzip-compressed (cloud-init detects and unpacks it), which keeps the
whole application under EC2's 16 KB user-data limit.
"""
from __future__ import annotations

import gzip
from pathlib import Path

USER_DATA_LIMIT = 16 * 1024
RUNTIME_REQUIREMENTS = ["boto3>=1.34", "requests>=2.31", "flask>=3.0", "waitress>=3.0",
                        "tzdata>=2024.1"]
APP_ROOT = "/opt/app"

_TEMPLATE = '''#!/usr/bin/env python3
"""Boot script for the {tier} tier. Generated by stack/boot.py. Runs once, as root."""
import os
import pathlib
import subprocess
import time

TIER = {tier!r}
APP = pathlib.Path({app_root!r})
FILES = {files!r}
ENV = {env!r}
REQUIREMENTS = {requirements!r}
SERVICE = """[Unit]
Description=Weather Advisor {tier} tier
After=network-online.target
Wants=network-online.target

[Service]
EnvironmentFile=/etc/weather-advisor/{tier}.env
WorkingDirectory={app_root}
ExecStart={app_root}/.venv/bin/python -m {module}
Restart=always
RestartSec=3
User=ec2-user

[Install]
WantedBy=multi-user.target
"""
LOG = pathlib.Path("/var/log/weather-advisor-boot.log")


def log(message):
    with LOG.open("a") as fh:
        fh.write(time.strftime("%H:%M:%S ") + message + "\\n")


def run(args, attempts=3):
    """Run one program (argument list, no shell). Retry, because package mirrors flap."""
    for attempt in range(1, attempts + 1):
        result = subprocess.run(args, capture_output=True, text=True)
        if result.returncode == 0:
            log("ok: " + " ".join(args[:3]))
            return
        log(f"attempt {{attempt}} failed: {{' '.join(args[:3])}}: {{result.stderr[-300:]}}")
        time.sleep(5 * attempt)
    raise SystemExit(f"giving up on {{args[0]}}")


def main():
    log("boot start, tier " + TIER)
    for rel, text in FILES.items():
        path = APP / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    run(["dnf", "install", "-y", "python3.11", "python3.11-pip"])
    run(["python3.11", "-m", "venv", str(APP / ".venv")])
    run([str(APP / ".venv/bin/pip"), "install", "--quiet", *REQUIREMENTS])

    env_dir = pathlib.Path("/etc/weather-advisor")
    env_dir.mkdir(mode=0o755, exist_ok=True)
    env_file = env_dir / (TIER + ".env")
    env_file.write_text("".join(f"{{k}}={{v}}\\n" for k, v in ENV.items()))
    os.chmod(env_file, 0o600)          # settings only; no secret is ever written here

    run(["chown", "-R", "ec2-user:ec2-user", str(APP)])
    pathlib.Path("/etc/systemd/system/weather-advisor-" + TIER + ".service").write_text(SERVICE)
    run(["systemctl", "daemon-reload"])
    run(["systemctl", "enable", "--now", "weather-advisor-" + TIER + ".service"])
    log("boot done")


main()
'''


def package_files(package_dir: Path) -> dict[str, str]:
    """{relative path: source} for every .py file of one tier's package."""
    package_dir = Path(package_dir)
    return {f"{package_dir.name}/{p.relative_to(package_dir).as_posix()}": p.read_text()
            for p in sorted(package_dir.rglob("*.py")) if "__pycache__" not in p.parts}


def build_boot_script(tier: str, package_dir: Path, env: dict[str, str]) -> str:
    """The Python boot program for one tier, with its code and settings embedded."""
    for key, value in env.items():
        if "\n" in str(value) or "=" in key:
            raise ValueError(f"bad setting {key!r}")
    return _TEMPLATE.format(tier=tier, app_root=APP_ROOT, files=package_files(package_dir),
                            env={k: str(v) for k, v in env.items()},
                            requirements=RUNTIME_REQUIREMENTS,
                            module=f"{Path(package_dir).name}.service")


def compress(script: str) -> bytes:
    """gzip with a fixed timestamp, so the same input always gives the same bytes."""
    return gzip.compress(script.encode(), mtime=0)
